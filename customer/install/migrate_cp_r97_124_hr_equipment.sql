-- GAS-CP-R97-124 (v1.188.0) — HR: equipment issued to employees, acceptance by the employee, handover lists accepted by HR
CREATE TABLE IF NOT EXISTS hr_eq_docs (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  person_id INT UNSIGNED NOT NULL,
  kind VARCHAR(8) NOT NULL DEFAULT 'issue',
  doc_no VARCHAR(24) NOT NULL,
  doc_date DATE NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'sent',
  note VARCHAR(500) NULL,
  created_by INT UNSIGNED NULL,
  created_name VARCHAR(160) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  emp_at DATETIME NULL,
  emp_via VARCHAR(8) NULL,
  emp_by INT UNSIGNED NULL,
  emp_name VARCHAR(160) NULL,
  emp_ip VARCHAR(64) NULL,
  emp_remark VARCHAR(500) NULL,
  hr_at DATETIME NULL,
  hr_by INT UNSIGNED NULL,
  hr_name VARCHAR(160) NULL,
  reminded_at DATETIME NULL,
  UNIQUE KEY uq_hr_eq_doc_no (doc_no),
  KEY ix_hr_eq_doc_person (person_id, kind, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS hr_eq_items (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  person_id INT UNSIGNED NOT NULL,
  category VARCHAR(16) NOT NULL DEFAULT 'other',
  description VARCHAR(200) NOT NULL,
  serial_no VARCHAR(80) NULL,
  asset_tag VARCHAR(40) NULL,
  qty DECIMAL(8,2) NOT NULL DEFAULT 1,
  size VARCHAR(20) NULL,
  cond_out VARCHAR(12) NOT NULL DEFAULT 'new',
  note VARCHAR(300) NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'draft',
  issue_doc_id INT UNSIGNED NULL,
  issued_on DATE NULL,
  return_doc_id INT UNSIGNED NULL,
  returned_on DATE NULL,
  cond_in VARCHAR(12) NULL,
  return_note VARCHAR(300) NULL,
  src_id INT UNSIGNED NULL,
  clone_of INT UNSIGNED NULL,
  created_by INT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY ix_hr_eq_item_person (person_id, status),
  KEY ix_hr_eq_item_issue (issue_doc_id),
  KEY ix_hr_eq_item_return (return_doc_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
