-- GAS-CP-R95-001 — website visitor statistics pulled from goldenas.com.gr (aggregates only, no personal data)
CREATE TABLE IF NOT EXISTS web_stats_day (
  d DATE NOT NULL, dim VARCHAR(12) NOT NULL, k VARCHAR(80) NOT NULL,
  n INT UNSIGNED NOT NULL DEFAULT 0, u INT UNSIGNED NOT NULL DEFAULT 0, x INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (d, dim, k), KEY ix_ws_dim (dim, d)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS web_stats_hour (d DATE NOT NULL, h TINYINT UNSIGNED NOT NULL, n INT UNSIGNED NOT NULL DEFAULT 0, u INT UNSIGNED NOT NULL DEFAULT 0, PRIMARY KEY (d, h)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
