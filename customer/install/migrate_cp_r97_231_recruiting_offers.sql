-- GAS-CP-R97-231 — recruiting: the offer to a candidate (financial proposal and terms, job description included), kept as a record (key r99n)
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS rc_offers (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  application_id INT UNSIGNED NOT NULL,
  offer_no VARCHAR(40) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'draft',
  position VARCHAR(190) NOT NULL,
  net_salary DECIMAL(10,2) NULL,
  currency VARCHAR(3) NOT NULL DEFAULT 'EUR',
  salary_per VARCHAR(8) NOT NULL DEFAULT 'month',
  payments_per_year TINYINT UNSIGNED NULL,
  contract VARCHAR(12) NOT NULL DEFAULT 'indefinite',
  start_date DATE NULL,
  hours VARCHAR(120) NULL,
  place VARCHAR(160) NULL,
  probation_months TINYINT UNSIGNED NULL,
  benefits TEXT NULL,
  terms TEXT NULL,
  valid_until DATE NULL,
  jd_id INT UNSIGNED NULL,
  jd_text MEDIUMTEXT NULL,
  subject VARCHAR(200) NULL,
  body MEDIUMTEXT NULL,
  sent_at DATETIME NULL,
  sent_by INT UNSIGNED NULL,
  sent_name VARCHAR(120) NULL,
  outcome_at DATETIME NULL,
  outcome_note VARCHAR(300) NULL,
  created_by INT UNSIGNED NULL,
  created_name VARCHAR(120) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY ix_rco_app (application_id), KEY ix_rco_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
