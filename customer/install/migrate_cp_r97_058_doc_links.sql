-- GAS-CP-R97-058 (v1.152.0) — Acceptance by e-mail link: one personal link per document and recipient, confirmed with a 6-digit code
CREATE TABLE IF NOT EXISTS doc_links (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  doc VARCHAR(10) NOT NULL,
  doc_id INT UNSIGNED NOT NULL,
  doc_no VARCHAR(80) NULL,
  doc_title VARCHAR(160) NULL,
  token_hash CHAR(64) NOT NULL,
  email VARCHAR(190) NOT NULL,
  name VARCHAR(120) NULL,
  lang VARCHAR(5) NOT NULL DEFAULT 'en',
  created_by INT UNSIGNED NULL,
  created_name VARCHAR(120) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at DATETIME NOT NULL,
  opened_at DATETIME NULL,
  code_hash CHAR(64) NULL,
  code_expires DATETIME NULL,
  code_at DATETIME NULL,
  code_sent SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  code_tries SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  fails SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  verified_at DATETIME NULL,
  pass_hash CHAR(64) NULL,
  used_at DATETIME NULL,
  used_ip VARCHAR(64) NULL,
  decision VARCHAR(20) NULL,
  signer_name VARCHAR(120) NULL,
  signer_role VARCHAR(80) NULL,
  cancelled_at DATETIME NULL,
  cancel_note VARCHAR(60) NULL,
  remind_n TINYINT UNSIGNED NOT NULL DEFAULT 0,
  last_remind_at DATETIME NULL,
  UNIQUE KEY uq_dl_token (token_hash),
  KEY ix_dl_doc (doc, doc_id),
  KEY ix_dl_open (used_at, cancelled_at, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
